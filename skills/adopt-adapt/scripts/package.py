NAME = "adopt-adapt"  # R3: was adopt-adapt-v2
VERSION = "3.0.0-grok-draft.r13-portfolio.1"
REQUIRED = {"references/re-methods.md", "references/re-source-review-2026-10-10.md", "tests/test_re_methods.py", "SKILL.md", "agents/openai.yaml", "scripts/aa.py", "scripts/package.py", "references/routing.md", "references/profiles/radar.md", "references/profiles/maginot.md", "references/profiles/eddie.md", "references/profiles/coding-workflow.md", "references/profiles/self.md", "references/profiles/generic.md", "references/due-diligence.md", "references/transfer.md", "references/python-to-typescript.md", "references/records.md", "references/evaluation.md", "references/evolution.md", "references/lessons.md", "references/output-template.md", "references/legal.md", "references/closed-source.md", "references/web-forensics.md", "references/re-verification.md", "references/hook-intake.md", "references/checker-honesty.md", "references/legal-research.md", "CHANGES.md", "evals/trigger-evals.json", "tests/test_aa.py", "tests/test_package.py", "tests/calibration-cases.json"}
REQUIRED |= {"scripts/execution.py", "scripts/research.py", "references/execution.md", "tests/test_execution.py", "tests/test_research.py", "tests/test_evidence_workflow.py"}
REQUIRED |= {"references/narrative-review.md", "tests/test_narrative_scope.py"}


def check(condition, message):
    if not condition:
        raise ValueError(message)


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def inventory(root):
    root = Path(root)
    check(root.is_dir() and not root.is_symlink() and not (hasattr(root, "is_junction") and root.is_junction()), "package root is absent or linked")
    result = {}
    for path in sorted(root.rglob("*")):
        check(not path.is_symlink() and not (hasattr(path, "is_junction") and path.is_junction()), "package contains linked paths")
        if path.is_file() and path.relative_to(root).as_posix() != "release.json":
            result[path.relative_to(root).as_posix()] = sha(path)
    return result


def manifest(root):
    root = Path(root)
    files = inventory(root)
    check(REQUIRED <= files.keys(), "required package resource missing")
    check(not any("__pycache__" in p or p.endswith(".pyc") for p in files), "remove generated bytecode before packaging")
    body = (root / "SKILL.md").read_text(encoding="utf-8")
    check(body.startswith("---\nname: adopt-adapt\n") and len(body.split()) > 300, "missing/empty skill body or wrong identity")
    return {"name": NAME, "version": VERSION, "baseline": "adopt-adapt 3.0.0-grok-draft.r13; lineage: 2.11.0 + adopt-adapt-v2 2.0.0 + 3.0.0-proposal", "files": files, "verification_scope": "Exact packaged bytes and required resources; not semantic behavior or native loading.", "host_prevents_freeform_final": False, "opaque_analysis_expansion": "unapproved-disabled", "release_status": "DRAFT", "release_checklist": {"steps_1_4": "structural: frontmatter, links, required files, manifest, helper-script unit tests", "steps_5_7_not_run": ["5 host trigger tests (Claude Code, Codex, Cursor)", "6 paired with/without-skill runs", "7 planted ordering/injection tests"], "unit_test_scope": "package structure and helper scripts (aa.py, package.py) only; not skill behaviour or verdict quality"}}


def verify(root, expected=None):
    root = Path(root)
    path = root / "release.json"
    check(not path.is_symlink(), "manifest must not be linked")
    value = json.loads(path.read_text(encoding="utf-8"))
    check(value == manifest(root), "package differs from manifest or fixed release contract")
    if expected is not None:
        check(value == json.loads(Path(expected).read_text(encoding="utf-8")), "installed manifest differs from expected release")
    return value


def checked_target(path):
    raw = Path(path).absolute()
    check(raw.name == NAME, f"destination must be named {NAME}")
    check(not raw.is_symlink() and not (hasattr(raw, "is_junction") and raw.is_junction()), "destination must not be linked")
    resolved = raw.resolve()
    check(resolved.parent != resolved and resolved.name == NAME, "invalid resolved destination")
    # Both install and recursive rollback operate only on this exact named child.
    check(resolved.is_relative_to(raw.parent.resolve()), "destination escapes intended parent")
    return resolved


def install(source, destination):
    source = Path(source).resolve()
    expected = verify(source)
    destination = checked_target(destination)
    check(not destination.exists(), "destination already exists; refusing to overwrite")
    destination.parent.mkdir(parents=True, exist_ok=True)
    stage = Path(tempfile.mkdtemp(prefix=".adopt-adapt-", dir=destination.parent)).resolve()
    try:
        # copytree is unnecessary: copy exactly the manifest's files plus the manifest.
        for name in [*expected["files"], "release.json"]:
            target = stage / name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source / name, target)
        verify(stage, source / "release.json")
        check(not destination.exists(), "destination appeared during staging")
        stage.rename(destination)
        verify(destination, source / "release.json")
    finally:
        if stage.exists():
            check(stage.parent == destination.parent and stage.name.startswith(".adopt-adapt-"), "unsafe staging cleanup")
            shutil.rmtree(stage)
    return str(destination)


def uninstall(destination, expected):
    destination = checked_target(destination)
    verify(destination, expected)
    # Reverify root/contents immediately before deletion; refuse any local file changes.
    check(checked_target(destination) == destination, "destination changed")
    verify(destination, expected)
    shutil.rmtree(destination)
    return str(destination)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("manifest", "verify"):
        p = sub.add_parser(name); p.add_argument("source")
    p = sub.add_parser("install"); p.add_argument("source"); p.add_argument("destination")
    p = sub.add_parser("uninstall"); p.add_argument("destination"); p.add_argument("--expected-manifest", required=True)
    args = parser.parse_args(argv)
    try:
        if args.command == "manifest":
            root = Path(args.source)
            value = manifest(root)
            output = root / "release.json"
            check(not output.is_symlink(), "manifest output is linked")
            output.write_text(json.dumps(value, indent=2) + "\n", encoding="utf-8", newline="\n")
            print(f"Manifested {len(value['files'])} files; no runtime certification.")
        elif args.command == "verify":
            value = verify(args.source); print(f"Verified {len(value['files'])} file hashes and fixed package contract.")
        elif args.command == "install":
            print(install(args.source, args.destination))
        elif args.command == "uninstall":
            print(f"Removed exact verified bundle: {uninstall(args.destination, args.expected_manifest)}")
        return 0
    except (OSError, ValueError, TypeError, KeyError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
